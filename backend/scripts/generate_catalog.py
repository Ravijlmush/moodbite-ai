def _item(
    item_id: str,
    restaurant_id: str,
    name: str,
    category: str,
    dietary_type: str,
    price_inr: int,
    mood_tags: list[str],
    sensory_tags: list[str],
    *,
    dietary_tags: list[str] | None = None,
    allergens: list[str] | None = None,
    prep_time_mins: int = 12,
    effort_to_eat: str = "zero_mess",
    dopamine_score: float = 0.80,
    heavy_index: float = 0.55,
    pairing_affinities: list[str] | None = None,
    is_available: bool = True,
) -> dict[str, Any]:
    tags = list(dietary_tags or [])
    if dietary_type == "veg" and "veg" not in tags:
        tags.insert(0, "veg")
    return {
        "id": item_id,
        "restaurant_id": restaurant_id,
        "name": name,
        "category": category,
        "dietary_type": dietary_type,
        "dietary_tags": tags,
        "allergens": allergens or [],
        "price_inr": price_inr,
        "prep_time_mins": prep_time_mins,
        "mood_tags": mood_tags,
        "sensory_tags": sensory_tags,
        "effort_to_eat": effort_to_eat,
        "dopamine_score": dopamine_score,
        "heavy_index": heavy_index,
        "pairing_affinities": pairing_affinities or [],
        "is_available": is_available,
    }


