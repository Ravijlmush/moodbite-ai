def validate_catalog(restaurants: list[dict[str, Any]], items: list[dict[str, Any]]) -> None:
    rest_ids = {r["id"] for r in restaurants}
    item_by_id = {it["id"]: it for it in items}
    assert len(rest_ids) == len(restaurants), "Duplicate restaurant IDs"
    assert len(item_by_id) == len(items), "Duplicate menu item IDs"
    assert len(items) >= 150, f"Expected >= 150 items, got {len(items)}"

    boosters_by_rest: dict[str, list[dict[str, Any]]] = {}
    for it in items:
        assert it["restaurant_id"] in rest_ids, f"Invalid restaurant_id on {it['id']}"
        if it["category"] in ("beverage", "dessert"):
            boosters_by_rest.setdefault(it["restaurant_id"], []).append(it)
        for aff in it["pairing_affinities"]:
            assert aff in item_by_id, f"Missing pairing affinity {aff} on {it['id']}"
            assert item_by_id[aff]["restaurant_id"] == it["restaurant_id"], (
                f"Cross-restaurant affinity {aff} on {it['id']}"
            )

    for r in restaurants:
        assert len(boosters_by_rest.get(r["id"], [])) >= 2, (
            f"Restaurant {r['id']} needs >= 2 boosters for Swap Drink support"
        )


def main() -> None:
    restaurants = build_restaurants()
    items = build_menu_items()
    validate_catalog(restaurants, items)

    CATALOG_PATH.parent.mkdir(parents=True, exist_ok=True)
    payload = {"restaurants": restaurants, "menu_items": items}
    CATALOG_PATH.write_text(json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8")

    mains = sum(1 for i in items if i["category"] not in ("beverage", "dessert"))
    boosters = sum(1 for i in items if i["category"] in ("beverage", "dessert"))
    print(f"Catalog generated successfully: {len(restaurants)} restaurants, {len(items)} items ({mains} mains, {boosters} boosters) -> {CATALOG_PATH}")


if __name__ == "__main__":
    main()
